def test_plot_sigma_vs_ti_produces_nonempty_png(tmp_path: Path) -> None:
    e_grid = np.array([0.03, 0.05, 0.08, 0.10, 0.12, 0.15])
    sigma_td = np.array([0.5, 1.2, 2.0, 1.8, 1.0, 0.3])
    sigma_ti = np.array([0.4, 1.1, 2.1, 1.9, 0.9, 0.25])
    usable = (0.05, 0.12)
    out = tmp_path / "sigma.png"
    plot_sigma_vs_ti(e_grid, sigma_td, sigma_ti, usable, out)
    assert out.exists() and out.stat().st_size > 0


def test_plot_sigma_vs_ti_multichannel_produces_nonempty_png(tmp_path: Path) -> None:
    e_grid = np.array([0.03, 0.05, 0.08, 0.10])
    sigma_td = np.array([[0.5, 0.1], [1.2, 0.2], [2.0, 0.3], [1.8, 0.25]])
    sigma_ti = sigma_td * 0.95
